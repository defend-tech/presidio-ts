  override validateResult(patternText: string): boolean | null {
    const value = patternText.replace(/[- :]/g, "");
    if (value.length < 8) return null;
    const prefix = value.slice(0, 2).toUpperCase();
    if (!InVehicleRegistrationRecognizer.PREFIXES.has(prefix)) return null;
    if (/^\d/.test(value[2] ?? "")) {
      const district = /^\d/.test(value[3] ?? "") ? value.slice(2, 4) : value[2];
      const registration = value.slice(-4);
      const districts =
        InVehicleRegistrationRecognizer.DISTRICTS[prefix] ?? new Set<string>();
      if (
        /^\d{4}$/.test(registration) &&
        Number(registration) > 0 &&
        Number(registration) <= 9999 &&
        (districts.has(district) || districts.has(String(Number(district))))
      )
        return true;
    }
    for (const code of InVehicleRegistrationRecognizer.DIPLOMATIC_CODES) {
      const index = value.indexOf(code);
      if (index !== -1) {
        const mission = value.slice(0, index);
        if (
          /^\d+$/.test(mission) &&
          ((Number(mission) >= 1 && Number(mission) <= 80) ||
            InVehicleRegistrationRecognizer.FOREIGN_MISSION_CODES.has(Number(mission)))
        )
          return true;
      }
    }
    return null;
  }
